# This script generates the Miha Translate Android launcher icons and the Fastlane store icon.
#
# The artwork is defined once below, on the 108x108 adaptive icon canvas, and is written out as:
#   - adaptive icon vector drawables (background, foreground, monochrome) in android/app/src/main/res/drawable/
#   - adaptive icon definitions in android/app/src/main/res/mipmap-anydpi-v26/
#   - legacy square and round PNGs for every density in android/app/src/main/res/mipmap-*/
#   - the 1024x1024 store icon in fastlane/metadata/android/en-US/images/icon.png
#
# Requires only Pillow. Run from the repository root:
#   python3 scripts/python/generate_launcher_icons.py [--preview <out.png>]
import argparse
import os

from PIL import Image, ImageDraw

RES_DIR = "android/app/src/main/res"
STORE_ICON = "fastlane/metadata/android/en-US/images/icon.png"

GRADIENT_START = "#29B6F6"  # top-left
GRADIENT_END = "#1565C0"  # bottom-right
WHITE = "#FFFFFF"
LIGHT_BLUE = "#B3E5FC"

CANVAS = 108  # adaptive icon canvas, in dp
SAFE_RADIUS = 33  # the 66dp safe zone circle

# Each shape is (fill color, polygon points) on the 108x108 canvas.
SHAPES = [
    # Bold M
    (WHITE, [
        (34, 70), (34, 40), (43, 40), (54, 54), (65, 40), (74, 40),
        (74, 70), (65, 70), (65, 55), (57.5, 65), (50.5, 65), (43, 55), (43, 70),
    ]),
    # Upper arrow, pointing right
    (WHITE, [(42, 29.5), (61, 29.5), (61, 25), (70, 32), (61, 39), (61, 34.5), (42, 34.5)]),
    # Lower arrow, pointing left
    (LIGHT_BLUE, [(66, 75.5), (47, 75.5), (47, 71), (38, 78), (47, 85), (47, 80.5), (66, 80.5)]),
]

# Legacy (pre-adaptive) icons show the centre of the canvas, like launchers do with adaptive icons.
LEGACY_CROP = 76
LEGACY_DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
LEGACY_PADDING = 2 / 48  # matches the 1dp transparent border of the standard 48dp legacy icon grid
LEGACY_CORNER = 0.16  # corner radius of the legacy square icon, as a fraction of its size
STORE_SIZE = 1024
SUPERSAMPLE = 4

ADAPTIVE_ICON = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""

BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/python/generate_launcher_icons.py, do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{CANVAS}dp"
    android:height="{CANVAS}dp"
    android:viewportWidth="{CANVAS}"
    android:viewportHeight="{CANVAS}">
    <path android:pathData="M0,0h{CANVAS}v{CANVAS}h-{CANVAS}z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="{CANVAS}"
                android:endY="{CANVAS}"
                android:startColor="{GRADIENT_START}"
                android:endColor="{GRADIENT_END}"/>
        </aapt:attr>
    </path>
</vector>
"""


def fmt(value):
    return f"{value:g}"


def path_data(points):
    head, *tail = points
    return f"M{fmt(head[0])},{fmt(head[1])}" + "".join(f"L{fmt(x)},{fmt(y)}" for x, y in tail) + "Z"


def vector(colors):
    paths = "".join(
        f'    <path\n        android:fillColor="{color}"\n        android:pathData="{path_data(points)}"/>\n'
        for color, points in colors
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/python/generate_launcher_icons.py, do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{CANVAS}dp"
    android:height="{CANVAS}dp"
    android:viewportWidth="{CANVAS}"
    android:viewportHeight="{CANVAS}">
{paths}</vector>
"""


def hex_rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def render_canvas(size):
    """Render the full 108dp canvas (background + foreground) at size x size pixels."""
    horizontal = Image.linear_gradient("L").rotate(90).resize((size, size))
    vertical = Image.linear_gradient("L").resize((size, size))
    # (x + y) / 2, i.e. the projection onto the top-left to bottom-right diagonal
    mask = Image.blend(horizontal, vertical, 0.5)
    image = Image.composite(
        Image.new("RGBA", (size, size), hex_rgb(GRADIENT_END)),
        Image.new("RGBA", (size, size), hex_rgb(GRADIENT_START)),
        mask,
    )
    draw = ImageDraw.Draw(image)
    scale = size / CANVAS
    for color, points in SHAPES:
        draw.polygon([(x * scale, y * scale) for x, y in points], fill=hex_rgb(color))
    return image


def render_icon(size, crop, shape):
    """Render the centre `crop` dp of the canvas into a size x size icon with the given mask shape."""
    big = size * SUPERSAMPLE
    padding = round(big * LEGACY_PADDING) if shape != "full" else 0
    inner = big - 2 * padding
    canvas = render_canvas(round(inner * CANVAS / crop))
    offset = (canvas.width - inner) // 2
    content = canvas.crop((offset, offset, offset + inner, offset + inner))

    mask = Image.new("L", (inner, inner), 0)
    draw = ImageDraw.Draw(mask)
    if shape == "round":
        draw.ellipse((0, 0, inner - 1, inner - 1), fill=255)
    elif shape == "square":
        draw.rounded_rectangle((0, 0, inner - 1, inner - 1), radius=round(inner * LEGACY_CORNER), fill=255)
    else:
        draw.rectangle((0, 0, inner, inner), fill=255)

    icon = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    icon.paste(content, (padding, padding), mask)
    return icon.resize((size, size), Image.LANCZOS)


def check_safe_zone():
    centre = CANVAS / 2
    for _, points in SHAPES:
        for x, y in points:
            distance = ((x - centre) ** 2 + (y - centre) ** 2) ** 0.5
            assert distance <= SAFE_RADIUS, f"({x}, {y}) is outside the adaptive icon safe zone"


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as file:
        file.write(content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", help="also write a contact sheet of the rendered icons to this path")
    args = parser.parse_args()

    check_safe_zone()

    write(f"{RES_DIR}/drawable/ic_launcher_background.xml", BACKGROUND)
    write(f"{RES_DIR}/drawable/ic_launcher_foreground.xml", vector(SHAPES))
    # The system tints the monochrome layer, so only the alpha of each path matters.
    write(f"{RES_DIR}/drawable/ic_launcher_monochrome.xml", vector([(WHITE, points) for _, points in SHAPES]))
    for name in ("ic_launcher", "ic_launcher_round"):
        write(f"{RES_DIR}/mipmap-anydpi-v26/{name}.xml", ADAPTIVE_ICON)

    rendered = []
    for density, size in LEGACY_DENSITIES.items():
        for name, shape in (("ic_launcher", "square"), ("ic_launcher_round", "round")):
            icon = render_icon(size, LEGACY_CROP, shape)
            icon.save(f"{RES_DIR}/mipmap-{density}/{name}.png", optimize=True)
            rendered.append(icon)

    store = render_icon(STORE_SIZE, LEGACY_CROP, "full").convert("RGB")
    store.save(STORE_ICON, optimize=True)

    if args.preview:
        sheet = Image.new("RGBA", (1024 + 16 + sum(i.width + 16 for i in rendered), 1024), (255, 255, 255, 255))
        sheet.paste(store, (0, 0))
        x = 1024 + 16
        for icon in rendered:
            sheet.alpha_composite(icon, (x, 0))
            x += icon.width + 16
        sheet.save(args.preview)


if __name__ == "__main__":
    main()
